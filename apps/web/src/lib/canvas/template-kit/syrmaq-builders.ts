/**
 * The opening screen.
 *
 * The photograph runs as a full-bleed horizontal band rather than filling the
 * screen vertically, which is the opposite of all 52 reference cards. That is
 * partly a compositional choice and partly honesty about the picture: what
 * makes the steppe shot work is its width and the emptiness above the
 * horizon, and a vertical crop throws exactly that away.
 *
 * It also fixes the type. The sky in that frame measures #e1e1dd — near
 * white — so white names laid over it would have no contrast at all. The
 * names sit below on the wool instead, in dark ink, at 74px.
 */
