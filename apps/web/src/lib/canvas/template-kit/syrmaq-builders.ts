/**
 * Sections for «Сырмақ» — қыз ұзату.
 *
 * Written after reading the first screen of all 22 ұзату and all 30 үйлену
 * тойы templates at toi.com.kz, plus the wedding catalogue at shaqyru24.
 * Three things are true of all 52 of them, and this template is built to be
 * none of them:
 *
 *  - Every single one is a centred vertical poster. Not one breaks the centre
 *    axis, and not one lets a photograph run off an edge. So this one is set
 *    on a left margin throughout, and its artwork bleeds past both edges.
 *  - Ornament is never the primary graphic. It appears as a thin gold
 *    filigree border or an arch, at caption scale. Here ою runs at
 *    architectural scale — a full-width frieze of real syrmaq felt, and
 *    medallions large enough to be cropped by the page.
 *  - The palette is always European bridal: cream and gold, blush, wine,
 *    emerald. This one is taken off a felt carpet instead — undyed wool,
 *    madder, ochre, dark brown — and carries no gold at all.
 *
 * ұзату is an «ақ» rite: ақ дастархан, ақ бата, ақ жол. A dark ground fights
 * that, which is why this stays light even though a dark card would stand out
 * more in a catalogue grid.
 */
