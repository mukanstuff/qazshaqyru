export function getSeoLanding(key: SeoLandingKey, locale: 'ru' | 'kz' = 'ru'): SeoLandingContent {
  if (locale === 'kz') {
    const kk = SEO_LANDINGS_KK[key];
    if (kk) return kk;
  }
  return SEO_LANDINGS[key];
}

export function isSeoLandingKey(value: string): value is SeoLandingKey {
  return value in SEO_LANDINGS;
}
